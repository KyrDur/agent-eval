async function prepare(page,request,{reviewed=false,slow=false,verify=true,missing=false}={}){
 const post=async(p,data)=>{const r=await request.post('/api/experiments'+p,{data});expect(r.ok(),await r.text()).toBeTruthy();return r.json()}
 const get=async p=>{const r=await request.get('/api/experiments'+p);expect(r.ok(),await r.text()).toBeTruthy();return r.json()}
 await page.goto('/')
 const key=randomBytes(24).toString('hex')
 const session=await post('/provider-sessions',{provider:'openai-compatible',base_url:`http://127.0.0.1:${providerPort}/v1`,model:slow?'background-slow-fixture':'phase4-rag',api_key:key,max_tokens:4096,max_calls:50})
 await post('/provider-sessions/'+session.provider_session_id+'/test',{})
 const pack=await get('/rag-policy-pack')
 const knowledge=await post('/knowledge-datasets',{name:'UX 验收 · 模拟政策',documents:pack.documents,metadata:{purpose:'UX_SCRIPTED_ACCEPTANCE_ONLY'}})
 const index=await post(`/knowledge-datasets/${knowledge.knowledge_dataset_id}/index`,{version:1,embedding_model:'sha256-lexical-bigram-v1',chunk_config:{chunk_size:100,chunk_overlap:10,algorithm:'normalized-character-window-v1'}})
 const cases=pack.debug_cases.slice(0,slow?1:2).map(c=>({...c,knowledge_requirements:{...c.knowledge_requirements,...(reviewed?{review_status:'CONFIRMED',source:'USER',reviewer:'软件验收声明，不是人工业务验证',reviewed_answer_hash:createHash('sha256').update(c.expected_answer).digest('hex')}:{review_status:'DRAFT'})}}))
 const ev=await post('/retrieval-evalsets',{name:'UX 验收 · 原题',index_id:index.index_id,cases})
 const run=await post('/retrieval-runs',{provider_session_id:session.provider_session_id,retrieval_eval_set_id:ev.retrieval_eval_set_id,retrieval_config:{top_k:1,rerank:true},verify_answers:verify})
 if(missing)await post('/provider-sessions/'+session.provider_session_id+'/clear',{})
 await page.evaluate(({sid,kid,iid,eid,rid})=>{localStorage.setItem('agenteval.workspace.v1',JSON.stringify({step:'evaluate',session:sid}));localStorage.setItem('agenteval.retrieval.v1',JSON.stringify({knowledge:kid,index:iid,evalSet:eid,baseline:rid,session:sid}))},{sid:session.provider_session_id,kid:knowledge.knowledge_dataset_id,iid:index.index_id,eid:ev.retrieval_eval_set_id,rid:run.run_id})
 await page.reload();await page.getByRole('button',{name:'继续上次实验',exact:true}).click()
 return {post,get,key,session,knowledge,index,ev,run}
}
