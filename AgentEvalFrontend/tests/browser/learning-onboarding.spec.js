import {test,expect} from '@playwright/test'
import path from 'node:path'
const evidence=process.env.AGENTEVAL_TEST_EVIDENCE_DIR
async function shot(page,name){if(evidence)await page.screenshot({path:path.join(evidence,name+'.png'),fullPage:true})}

test('Five concrete optimization examples stay read-only until a learner starts practice',async({page})=>{
 const errors=[],modelRequests=[]
 page.on('pageerror',e=>errors.push(e.message))
 page.on('request',r=>{if(r.method()==='POST'&&/provider-sessions|retrieval-runs|learning\/attempts/.test(r.url()))modelRequests.push(r.url())})
 await page.goto('/');await page.getByRole('button',{name:'先看一个完整案例 →',exact:true}).click()
 const guide=page.getByRole('region',{name:'完整评测示范'})
 await expect(page.getByRole('heading',{name:'先看五种改法怎么选'})).toBeVisible()
 const methods=guide.getByRole('navigation',{name:'五种改法'}).getByRole('button')
 await expect(methods).toHaveCount(5)
 for(let i=0;i<5;i++){
  await methods.nth(i).click()
  await expect(guide.getByRole('heading',{name:'先看这道题与本轮资料'})).toBeVisible()
  await guide.getByRole('button',{name:'下一步：查原因 →',exact:true}).click()
  await expect(guide.locator('.walkthrough-diagnosis>li')).toHaveCount(3)
  await guide.getByRole('button',{name:'下一步：试改法 →',exact:true}).click()
  if(i===0){await expect(guide.getByRole('region',{name:'资料重排原理图解'})).toBeVisible();await expect(guide.getByText('同时保留原文',{exact:true})).toBeVisible();await expect(guide.getByText('全部 4 条候选原文',{exact:true})).toBeVisible()}
  else await expect(guide.locator('.walkthrough-change-flow>article')).toHaveCount(2)
  await guide.getByRole('button',{name:'下一步：看对比 →',exact:true}).click()
  await expect(guide.getByRole('list',{name:'三道题的示例对比'}).getByRole('listitem')).toHaveCount(3)
  await guide.getByRole('button',{name:'下一步：做决定 →',exact:true}).click()
  await expect(guide.getByRole('heading',{name:'是否保留本次修改？'})).toBeVisible()
  if(i===2)await expect(guide.getByText('暂不保留这次从 3 条增至 5 条的修改。',{exact:true})).toBeVisible()
 }
 await shot(page,'onboarding-five-methods-desktop')
 await page.setViewportSize({width:390,height:844})
 expect(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+2)).toBe(false)
 await shot(page,'onboarding-five-methods-mobile')
 await expect(page.locator('.judgment-panel')).toHaveCount(0)
 await expect(guide.locator('textarea,input')).toHaveCount(0)
 expect(await (await page.request.get('/api/experiments/learning/attempts')).json()).toEqual([])
 expect(modelRequests).toEqual([])
 await guide.getByRole('button',{name:'继续证据判断练习 →',exact:true}).click()
 await expect(page.getByRole('heading',{name:'这句回答能信吗？',exact:true})).toBeVisible()
 await expect(page.locator('.learning-walkthrough')).toHaveCount(0)
 await expect(page.getByLabel('你的看法',{exact:true})).toHaveValue('')
 await expect(page.getByLabel('引用的原文',{exact:true})).toHaveValue('')
 expect(modelRequests).toHaveLength(1)
 const history=await (await page.request.get('/api/experiments/learning/attempts')).json()
 expect(history).toHaveLength(1);expect(history[0].case_id).toBe('p01');expect(history[0].stage).toBe('STARTED')
 expect(errors).toEqual([])
})

test('An existing KEEP decision resumes with context and examples without replacing learner work',async({page})=>{
 const errors=[];page.on('pageerror',e=>errors.push(e.message))
 await page.goto('/')
 const previousCount=(await (await page.request.get('/api/experiments/learning/attempts')).json()).length
 const post=async(url,data)=>{const r=await page.request.post('/api/experiments/learning'+url,{data:{...data,request_id:crypto.randomUUID()}});expect(r.ok(),await r.text()).toBeTruthy();return r.json()}
 const started=await post('/attempts',{case_id:'p01',mode:'TRAINING'})
 const id=started.attempt_id,source=started.case.evidence[0]
 await post(`/attempts/${id}/initial`,{judgment:'先检查当前订单的证据是否齐全。',evidence:[{evidence_id:source.evidence_id,quote:source.text}],candidate_causes:['UNCERTAIN'],uncertainty:'当前信息还不够。',distinguishing_check:'再查当前订单的实际记录。',source:'SELF'})
 await post(`/attempts/${id}/prediction`,{choice:'KEEP',expected_result:'先核对原始订单。',potential_cost:'本次还不能确认修改效果。',reason:'证据需要先核实。'})
 await post(`/attempts/${id}/replay`,{})
 await page.evaluate(id=>{localStorage.setItem('agenteval.workspace.v1',JSON.stringify({step:'learning'}));localStorage.setItem('agenteval.learning.attempt',id)},id)
 await page.reload()
 const panel=page.locator('.decision-panel')
 await expect(panel.getByRole('heading',{name:'对照结果，决定下一步'})).toBeVisible()
 await expect(panel.getByText(started.case.question,{exact:false})).toBeVisible()
 await expect(panel.getByText(/这次还没有改后的回答/)).toBeVisible()
 await expect(panel.getByRole('combobox',{name:'你的决定'}).locator('option')).toHaveCount(1)
 await expect(panel.getByLabel('为什么？',{exact:true})).toHaveValue('')
 await expect(panel.getByRole('complementary',{name:'填写示范'})).toBeVisible()
 await shot(page,'onboarding-resumed-decision-desktop')
 await panel.getByLabel('为什么？',{exact:true}).fill('先核实这笔订单的退款记录，再决定要不要修改评分方法。')
 await panel.getByLabel('还有哪些情况没试过？',{exact:true}).fill('修改是否有用还没测试，准备固定回答和规则后再比较。')
 await page.getByRole('button',{name:'回看完整示范',exact:true}).click()
 const guide=page.getByRole('region',{name:'完整评测示范'})
 await guide.getByRole('button',{name:/5\s*做决定/}).click()
 await guide.getByRole('button',{name:'回到正在做的题 →',exact:true}).click()
 await expect(panel.getByLabel('为什么？',{exact:true})).toHaveValue('先核实这笔订单的退款记录，再决定要不要修改评分方法。')
 await page.setViewportSize({width:390,height:844})
 expect(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+2)).toBe(false)
 await shot(page,'onboarding-resumed-decision-mobile')
 await panel.getByRole('button',{name:'记下我的决定',exact:true}).click()
 await expect(page.getByRole('button',{name:'再试一道类似的题 →',exact:true})).toBeVisible()
 const saved=await (await page.request.get('/api/experiments/learning/attempts/'+id)).json()
 expect(saved.initial_independent).toBe(true)
 expect(saved.events.filter(e=>e.name==='initial_judgment_saved')).toHaveLength(1)
 expect(saved.events.find(e=>e.name==='adoption_decided').payload).toEqual({decision:'KEEP',reason:'先核实这笔订单的退款记录，再决定要不要修改评分方法。',limitations:'修改是否有用还没测试，准备固定回答和规则后再比较。'})
 expect(await (await page.request.get('/api/experiments/learning/attempts')).json()).toHaveLength(previousCount+1)
 expect(errors).toEqual([])
})
