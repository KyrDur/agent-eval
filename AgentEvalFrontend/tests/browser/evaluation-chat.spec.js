 const change=await post('/retrieval-changes',{baseline_run_id:baseline.run_id,change_type:'TOP_K_CHANGE',after_config:{top_k:2},reason:'软件验收，只改返回数量',selected_case_ids:['chat_gap_0'],user_confirmed:true})
