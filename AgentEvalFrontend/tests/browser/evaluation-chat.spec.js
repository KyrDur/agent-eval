async function captureCopies(page){
 await page.addInitScript(()=>{window.reviewCopies=[];Object.defineProperty(navigator,'clipboard',{configurable:true,value:{writeText:async text=>window.reviewCopies.push(text)}})})
}
const copiedJson=text=>JSON.parse(text.split('```json\n')[1].split('\n```')[0])

