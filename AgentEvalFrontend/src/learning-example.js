export const walkthroughSteps = ['看案例', '查原因', '试改法', '看对比', '做决定']

export function writingExample(stage, kept = false, methodId = 'RERANK_TOGGLE') {
 const sample=optimizationExample(methodId)
 if(stage==='judgment')return [['你的看法',sample.judgment],['引用的原文',sample.quote]]
 if(stage==='cause')return [['可能的原因',sample.cause],['还没弄清','是否适用于其他问法，仍需复测。'],['再查什么',sample.check]]
 if(stage==='prediction')return [['预期结果',sample.prediction],['可能的新问题',sample.potentialCost]]
 return kept?[['为什么','这次暂未试改，还没有改后的结果，先补齐判断依据。'],['哪些情况没试过','候选改法是否有效、会不会影响原来答对的题，都还未验证。']]:[['本次决定',sample.decision],['为什么',sample.reason],['哪些情况没试过',sample.limitations]]
}
