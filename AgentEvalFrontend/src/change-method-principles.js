// Shared by teaching examples and real experiment controls.
export const changeMethodPrinciples = {
 KNOWLEDGE_UPDATE:{
  principle:'AI 核对本题记录，把已有参考答案原文补进知识库，并自动准备资料查找。',
  example:'参考答案写了补发配件的条件，就完整补到知识库，再用原题复测。',
  distinction:'改变的是资料内容。原题用于检查这次补充，仍需用其他题验证效果。',
 },
 EMBEDDING_CHANGE:{
  principle:'匹配模型把问题和资料转换成可比较的数字表示，用来找意思相近的内容。换模型后，需要用同版原文重新准备索引。',
  example:'用户说“进水”，资料写“进液损坏”，比较另一模型能否把两者匹配起来。',
  distinction:'更换的是资料匹配模型，回答模型不变；不同问法仍需复测，效果不一定都变好。',
 },
 RETRIEVAL_MODE_CHANGE:{
  principle:'关键词查找看型号、编号等文字是否匹配；语义查找看意思是否相近。两路结果合并排序后，再选出资料。',
  example:'查 X-17 时，用关键词区分型号，同时用语义理解“保修多久”的意思。',
  distinction:'这是改变查找方式，不是改写用户问题；用户没提供型号时，仍需先确认。',
 },
 QUERY_REWRITE_TOGGLE:{
  principle:'先把口语或省略的表达整理成适合查资料的问法，再检索。用户的原问题仍保留给回答模型。',
  example:'“钱啥时候回卡里”整理成“退款 银行卡 到账时间”，再去查资料。',
  distinction:'只换查找用语，不能擅自补成“退款已审核通过”，也不能补出缺失政策。',
 },
 CANDIDATE_POOL_CHANGE:{
  principle:'调整先找多少段资料来筛选，让更多片段有机会参与重排或混合查找的合并排序。',
  example:'先找 20 段改为 40 段来挑，最后给回答模型的上限仍是 3 段。',
  distinction:'候选范围决定“先找多少”；Top K 决定“最后给多少”。先启用重排或混合查找，再调整候选上限，才会影响筛选。',
 },
 RERANK_TOGGLE:{
  principle:'对已经找到的候选资料重新评估相关程度，再把排在前面的几条交给回答模型。',
  example:'关键条款原来排第 4，重排后进入前 3；最终参考条数仍保持不变。',
  distinction:'重排改变已有候选的顺序，不增加候选。没进入候选的资料，不能靠重排补出来。',
 },
 TOP_K_CHANGE:{
  principle:'从排好序的候选中，最多取前 K 段供回答参考。K 越大，模型可能看到的资料越多。',
  example:'原来给前 3 段，改为前 5 段，让第 4 段的例外也有机会被读到。',
  distinction:'这是改变“最后给多少”，先找来的候选范围不变。实际条数还受可用片段与上下文长度限制。',
 },
 CHUNKING_CHANGE:{
  principle:'先把长文档切成便于查找的小段。换一种切分边界并重新准备索引，检查条件和例外能否留在一起。',
  example:'把“一般七天可退”和紧接着的“已组装家具例外”，尽量保留在同一段。',
  distinction:'这是改变建索引前的切法；补前后文是在查到资料后再扩充。按条款切分也不保证所有条件都完整。',
 },
 CONTEXT_STRATEGY_CHANGE:{
  principle:'AI 查资料时可能只读到其中一段。这个改法把前后已有的说明也一起给它；页面会自动准备，不需要选择参数。',
  example:'原来只读到“5～7 个工作日退回”，现在也读到前面的“入库并审核通过后”。',
  distinction:'原资料不变，也不重新切块或建索引。若原来已带前后文，则试一次去掉它们，检查干扰是否减少；多读资料不保证答得更好。',
 },
 ANSWER_PROMPT_CHANGE:{
  principle:'调整给回答模型的工作要求，让它更明确地核对条件、处理信息不足并组织回答。',
  example:'追加“回答是否包邮前，先核对金额与收货地区；信息不足时先追问”。',
  distinction:'这是改变怎样使用已有资料，查找和评分规则不变。提示词不能替代缺失的业务知识。',
 },
}
